"""Morph detector contract and feature behaviour (§5.4 D2).

The corpus itself is never committed (LFW-derived, `data/LICENCES.md`), so these tests
must not depend on it. They cover what can be checked without it: the `Detector` contract,
the two ISO settings' distinct behaviour, the feature extractors' invariants, and the CLI.
Corpus-dependent numbers (ACER, MMPMR, cross-method generalisation) live in
`results/detectors/morph/results.json` and are regenerated by `make bench`, not asserted
here — a test that needs a 1200-image corpus to run is a test that does not run.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import cv2
import numpy as np
import pytest

from pqbio.config import settings
from pqbio.detect.base import Detector
from pqbio.detect.morph import (
    MorphDetector,
    _bsif_like_histogram,
    _lbp_histogram,
    dmad_features,
    smad_features,
)

REPO_ROOT = Path(__file__).resolve().parents[2]


def _face_image() -> np.ndarray:
    """A real photographed face — the only one available without a licensed dataset."""
    from skimage.data import astronaut

    return cv2.cvtColor(astronaut(), cv2.COLOR_RGB2BGR)


class TestDetectorContract:
    def test_implements_the_abc(self) -> None:
        assert issubclass(MorphDetector, Detector)

    def test_threshold_comes_from_config_not_a_constant(self) -> None:
        assert MorphDetector(setting="smad").threshold == settings.detect.thresholds.morph

    def test_dmad_without_a_live_capture_refuses_rather_than_degrading(self) -> None:
        """A D-MAD result computed without a reference is not a D-MAD result.

        Silently falling back to S-MAD would be worse than returning nothing: the caller
        would believe it had the stronger setting's answer.
        """
        score, reasons, _ = MorphDetector(setting="dmad").score_image(_face_image())
        assert score == 0.0
        assert any("NO_LIVE_CAPTURE" in r for r in reasons)

    def test_missing_model_is_reported_not_treated_as_benign(self) -> None:
        """`0.0` must never mean "checked and clean" when nothing was checked."""
        detector = MorphDetector(setting="smad", model_path=Path("does-not-exist.txt"))
        score, reasons, _ = detector.score_image(_face_image())
        assert score == 0.0
        assert any("MODEL_MISSING" in r for r in reasons)


class TestFeatures:
    def test_smad_feature_vector_is_fixed_length_and_finite(self) -> None:
        features = smad_features(_face_image())
        assert features.ndim == 1
        assert np.isfinite(features).all()
        # LBP(10) + BSIF-like(256) + blend residuals(7) + ArcFace(512)
        assert features.shape[0] == 10 + 256 + 7 + 512

    def test_smad_features_are_deterministic(self) -> None:
        """The BSIF-like bank is seeded; an unseeded bank would make every score
        irreproducible and every committed result unverifiable."""
        image = _face_image()
        assert np.array_equal(smad_features(image), smad_features(image))

    def test_histograms_are_normalised(self) -> None:
        gray = cv2.cvtColor(_face_image(), cv2.COLOR_BGR2GRAY)
        for hist in (_lbp_histogram(gray), _bsif_like_histogram(gray)):
            assert hist.sum() == pytest.approx(1.0)
            assert (hist >= 0).all()

    def test_dmad_features_are_antisymmetric_in_their_difference(self) -> None:
        """The signed embedding difference is the feature §5.4 D2 specifies, so swapping
        suspect and reference must negate it — if it did not, the feature would be
        measuring something other than the difference."""
        image = _face_image()
        flipped = cv2.flip(image, 1)
        forward = dmad_features(image, flipped)
        backward = dmad_features(flipped, image)
        assert forward is not None and backward is not None
        embedding_dim = 512
        assert forward[:embedding_dim] == pytest.approx(-backward[:embedding_dim], abs=1e-5)
        # |difference| and the cosine are symmetric by construction.
        assert forward[embedding_dim : 2 * embedding_dim] == pytest.approx(
            backward[embedding_dim : 2 * embedding_dim], abs=1e-5
        )

    def test_dmad_returns_none_when_no_face_is_present(self) -> None:
        blank = np.full((250, 250, 3), 128, dtype=np.uint8)
        assert dmad_features(blank, _face_image()) is None


class TestCLI:
    """§5.4's DoD: "Per-detector CLI: python -m pqbio.detect.<name> --input PATH"."""

    def test_cli_scores_a_single_image(self, tmp_path: Path) -> None:
        image_path = tmp_path / "suspect.png"
        cv2.imwrite(str(image_path), _face_image())
        out_path = tmp_path / "scores.json"

        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "pqbio.detect.morph",
                "--input",
                str(image_path),
                "--out",
                str(out_path),
            ],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=300,
        )
        assert result.returncode == 0, result.stderr

        payload = json.loads(out_path.read_text(encoding="utf-8"))
        assert payload["setting"] == "smad"
        assert 0.0 <= payload["score"] <= 1.0
        assert payload["threshold"] == settings.detect.thresholds.morph
        assert isinstance(payload["decision"], bool)

    def test_cli_selects_dmad_when_a_live_capture_is_given(self, tmp_path: Path) -> None:
        image = _face_image()
        suspect = tmp_path / "suspect.png"
        live = tmp_path / "live.png"
        cv2.imwrite(str(suspect), image)
        cv2.imwrite(str(live), cv2.flip(image, 1))
        out_path = tmp_path / "scores.json"

        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "pqbio.detect.morph",
                "--input",
                str(suspect),
                "--live",
                str(live),
                "--out",
                str(out_path),
            ],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=300,
        )
        assert result.returncode == 0, result.stderr
        assert json.loads(out_path.read_text(encoding="utf-8"))["setting"] == "dmad"


class TestCorpusManifest:
    """The manifest IS committed, so its claims can be checked without the images."""

    @pytest.fixture
    def manifest(self) -> dict:
        path = REPO_ROOT / "data" / "manifests" / "morph_corpus_manifest.json"
        if not path.is_file():
            pytest.skip("morph corpus manifest absent -- run scripts/make_morph_corpus.py")
        return dict(json.loads(path.read_text(encoding="utf-8")))

    def test_splits_are_subject_disjoint(self, manifest: dict) -> None:
        """§6's requirement, and the one most easily broken by a later change to pairing.

        The generator asserts this too; asserting it again here means a manifest that
        somehow shipped violating it cannot pass CI.
        """
        by_split: dict[str, set[str]] = {"train": set(), "test": set()}
        for sample in manifest["samples"]:
            by_split[sample["split"]].update(sample["contributors"])
        assert by_split["train"] & by_split["test"] == set()

    def test_at_least_two_morph_methods(self, manifest: dict) -> None:
        """One generator means the detector can only learn that generator (§12 item 10)."""
        methods = {s["method"] for s in manifest["samples"] if s["label"] == "morph"}
        assert len(methods) >= 2

    def test_every_morph_has_exactly_two_contributors(self, manifest: dict) -> None:
        for sample in manifest["samples"]:
            if sample["label"] == "morph":
                assert len(sample["contributors"]) == 2
                assert sample["contributors"][0] != sample["contributors"][1]

    def test_pair_selection_is_recorded_and_beats_random(self, manifest: dict) -> None:
        """Pairing must be non-random or the detector learns "implausible pair" instead of
        "morph". The manifest records both the chosen pairs' similarity and the population
        median so the claim is auditable rather than asserted."""
        selection = manifest["pair_selection"]
        chosen = [s["pair_cosine"] for s in manifest["samples"] if s["pair_cosine"] is not None]
        assert chosen
        assert float(np.median(chosen)) > selection["between_identity_cosine_median"]

    def test_corpus_images_are_not_committed(self) -> None:
        """LFW grants no redistribution right, so morphs derived from it stay out of git
        (`data/LICENCES.md`). The manifest is the committed artefact."""
        tracked = subprocess.run(
            ["git", "ls-files", "data/processed/"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )
        assert tracked.stdout.strip() == ""

    def test_pool_census_explains_the_identity_count(self, manifest: dict) -> None:
        """The pool size is a claim about LFW, so the manifest must carry the census that
        backs it: how many identities exist, how many have enough images to be usable, and
        why the floor sits where it does."""
        pool = manifest["pool"]
        assert pool["lfw_identities_total"] >= pool["lfw_identities_with_2plus_images"]
        assert pool["identities_usable"] <= pool["lfw_identities_with_2plus_images"]
        assert pool["min_faces_per_identity"] >= 2, (
            "below 2 images an identity's enrolment image is its morph's source image, "
            "and MMPMR would match a morph against its own photograph"
        )
        assert "why_this_pool" in pool

    def test_chosen_pair_cosine_distribution_is_recorded(self, manifest: dict) -> None:
        dist = manifest["pair_selection"]["chosen_pair_cosine"]
        assert dist["min"] <= dist["p25"] <= dist["median"] <= dist["p75"] <= dist["max"]


class TestVerifyingSubset:
    """Detection restricted to morphs that actually verify as both contributors (§12 item 8).

    Synthetic score rows with hand-computed expectations -- the logic is what is under test,
    not the corpus.
    """

    @staticmethod
    def _detection(n_genuine: int, verifying_scores: list[float], failed_scores: list[float]):  # type: ignore[no-untyped-def]
        rows = [
            {"path": f"g{i}", "label": "bona_fide", "method": None, "score": 0.1}
            for i in range(n_genuine)
        ]
        rows += [
            {"path": f"v{i}", "label": "morph", "method": "landmark_alpha", "score": sc}
            for i, sc in enumerate(verifying_scores)
        ]
        rows += [
            {"path": f"f{i}", "label": "morph", "method": "spliced_jpeg", "score": sc}
            for i, sc in enumerate(failed_scores)
        ]
        verifies = {f"v{i}": True for i in range(len(verifying_scores))}
        verifies.update({f"f{i}": False for i in range(len(failed_scores))})
        return {"_test_scores": rows}, verifies

    def test_blocks_below_the_floor_and_reports_the_count(self) -> None:
        from pqbio.detect.morph_eval import evaluate_verifying_subset

        floor = settings.detect.morph.min_verifying_attacks_reported
        detection, verifies = self._detection(40, [0.9] * (floor - 1), [0.9] * 50)
        cell = evaluate_verifying_subset(detection, verifies, threshold=0.5)

        assert cell.get("blocked") is True
        assert cell["n_test_morphs_verifying"] == floor - 1
        assert cell["n_test_morphs"] == floor - 1 + 50
        assert str(floor - 1) in cell["blocker"], "the count must be in the blocker text itself"

    def test_reports_metrics_at_the_floor_over_verifying_attacks_only(self) -> None:
        """30 verifying attacks, 6 missed (score below 0.5) -> APCER 0.2 exactly; the 50
        non-verifying morphs, all missed, must not move it."""
        from pqbio.detect.morph_eval import evaluate_verifying_subset

        floor = settings.detect.morph.min_verifying_attacks_reported
        verifying = [0.9] * (floor - 6) + [0.2] * 6
        detection, verifies = self._detection(40, verifying, [0.1] * 50)
        cell = evaluate_verifying_subset(detection, verifies, threshold=0.5)

        assert cell.get("blocked") is not True
        assert cell["n_attack"] == floor
        assert cell["n_genuine"] == 40
        assert cell["apcer"] == pytest.approx(6 / floor)
        lower, upper = cell["apcer_ci95"]
        assert lower < 6 / floor < upper

    def test_morphs_without_a_verification_result_are_counted_not_assumed(self) -> None:
        from pqbio.detect.morph_eval import evaluate_verifying_subset

        detection, verifies = self._detection(10, [0.9] * 5, [])
        del verifies["v0"]
        cell = evaluate_verifying_subset(detection, verifies, threshold=0.5)
        assert cell["n_test_morphs_verification_unknown"] == 1
        assert cell["n_test_morphs_verifying"] == 4


class TestPrecomputedEmbeddings:
    """The evaluation embeds each image once and passes the result in; that must not change
    a single feature value."""

    def test_smad_features_identical_with_precomputed_embedding(self) -> None:
        from pqbio.detect.morph import _embedding

        image = _face_image()
        assert np.array_equal(
            smad_features(image), smad_features(image, embedding=_embedding(image))
        )

    def test_smad_features_accept_an_explicit_no_face(self) -> None:
        """`None` means "no face found" and must zero the embedding block, distinct from
        "not supplied"."""
        features = smad_features(_face_image(), embedding=None)
        assert not features[-512:].any()

    def test_dmad_from_embeddings_matches_dmad(self) -> None:
        from pqbio.detect.morph import _embedding, dmad_features_from_embeddings

        image, flipped = _face_image(), cv2.flip(_face_image(), 1)
        direct = dmad_features(image, flipped)
        cached = dmad_features_from_embeddings(_embedding(image), _embedding(flipped))
        assert direct is not None and cached is not None
        assert np.array_equal(direct, cached)
